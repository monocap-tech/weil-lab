#!/usr/bin/env python3
"""NF470 exact-rational island promotion from native original J7 center source receipt.
The input must be generated by the pinned NF470 full original 4096-bit Arb evaluator.
No assumption about whole J7 integral or RH is made.
"""
from fractions import Fraction as F
import argparse,json
from pathlib import Path
B=F(11,10);x=F(21,20);r=F(1,2*10**16)
source_sha="0a83cdb71c7d7d0b412f30564aff34fb560140300e02fe08b28302d940b2fcce"
seam_sha="c2731e3bc422786a28cee7c058c1b41078e80935a6417ba1a149fba14c640675"
def main():
    p=argparse.ArgumentParser()
    p.add_argument("--source-receipt",required=True)
    p.add_argument("--output",required=True)
    a=p.parse_args()
    source=json.loads(Path(a.source_receipt).read_text())
    assert source["pass"]=="NF470" and source["mode"]=="joint-node"
    assert source["original_nf407_source_sha256"]==source_sha
    assert source["original_nf406_seams_sha256"]==seam_sha
    assert source["original_273_groups"] and source["original_246_sources"]
    assert source["genuine_original_J7_regular_prime_powers"]==[2,3,4,5,7,8]
    q=source["joint_point"]
    assert q["x"]=="21/20" and q["source_jet_center"]=="x (not B)"
    assert q["source_jet_order"]==1800 and q["native_bits"]>=4096
    zl,zu=map(F,q["original_full_J7_z_outward"])
    sl,su=map(F,q["original_pointwise_4pz_plus_2z2_outward"])
    assert 0<zl<zu<F(3,10**11)
    assert sl<su<-F(39,10**22) # strict negative actual whole signed point
    assert r<F(1,100) and F(26,25)<x-r<x+r<F(53,50)
    # Authentic original NF464 endpoint/principal ledger, absolute v and C7.
    vmax=F(117,10**13);Cmax=F(793,250)
    # d>B-x>= 1/26; B/d < B*26=28.6 < e^4:
    # e^4 > 1+4+4^2/2+4^3/6+4^4/24 > B*26.
    exp4_lower=sum((F(4)**k/F(__import__("math").factorial(k)) for k in range(5)),F(0))
    assert B*26<exp4_lower
    assert B-(x+r)>F(1,26)
    pmax=vmax*(Cmax+2)
    assert pmax<F(1,10**10)
    pprimemax=13*vmax
    assert pprimemax<F(1,10**8)
    # In collar, source true uniform |z'|<30000 from original NF417/418;
    # anchor z(x)<3e-11, so all z remain <1e-10 and positive.
    Mz=F(30000)
    assert zu+Mz*r<F(1,10**10)
    assert zl-Mz*r>0
    # For S=4pz+2z², |S'|<=4|p'||z|+4(|p|+|z|)|z'|.
    Ms=4*F(1,10**8)*F(1,10**10)+4*(F(1,10**10)+F(1,10**10))*Mz
    assert Ms<F(3,10**5)
    signed_upper=su+F(3,10**5)*r
    assert signed_upper<-F(24,10**22) # -2.4e-21
    interval_upper=2*r*signed_upper
    assert interval_upper<-F(2,10**37)
    out={
      "pass":"NF470",
      "standing":"source-certified original full signed J7 second island; exact rational radius and integrated sign",
      "source_receipt":a.source_receipt,
      "original_nf407_sha256":source_sha,"original_nf406_sha256":seam_sha,
      "center":"21/20","radius":str(r),
      "full_original_z_strict_positive":True,"full_original_signed_integrand_strict_negative":True,
      "full_original_signed_integral_strict_upper":"-2/10^37",
      "center_original_signed_source_outward":q["original_pointwise_4pz_plus_2z2_outward"],
      "original_source_derivative_bound":"30000",
      "whole_J7_signed":"OPEN","NF404":"OPEN","W_ODD_NEG":"OPEN","RH":"OPEN"
    }
    o=Path(a.output);o.parent.mkdir(parents=True,exist_ok=True)
    o.write_text(json.dumps(out,indent=2)+"\n")
    print("NF470 true original J7 second negative signed island PASSED; entire J7 remains OPEN")
if __name__=="__main__":main()
