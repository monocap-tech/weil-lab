def source_and_jump():
    outer,protect=protected_outer_band()
    clusters,width,mass,leaves,accepted=protected_inner_cover()
    assert outer==2535 and protect>KAPPA
    assert len(clusters)==107 and leaves==973 and accepted==9261
    assert width==F(973,32)
    assert len(ACTIVE)==7 and set(ACTIVE)=={2,3,4,5,7,8,9}
    assert (clusters[0][0]+clusters[0][1])/2==C0
    assert sum(taylor_order(r-l,9)[0] for l,r,_ in clusters)==469

    log2lo,log2hi=SHIFTS[2]
    assert 0<log2lo<log2hi<B
    # x0=B-ln2 strictly inside I and not a physical endpoint.
    x0lower,x0upper=B-log2hi,B-log2lo
    assert 0<x0lower<x0upper<B

    # Edges generated by original n-th shifts are
    #   B-ln n       from v(x+ln n) right endpoint,
    #   -B+ln n      from v(x-ln n) left endpoint,
    # whenever within [-B,B]. All other endpoints lie outside.
    # Strictly isolate x0=B-ln2 from EVERY other original
    # prime/power endpoint using ONLY certified original log intervals.
    distances={}
    for n in sorted(ACTIVE):
        lnlo,lnhi=SHIFTS[n]
        if n!=2:
            assert (lnhi<log2lo or lnlo>log2hi)
        # B-ln2 = -B+ln n would mean ln2+ln n=2B.
        summlo=log2lo+lnlo
        summhi=log2hi+lnhi
        assert (summhi<2*B or summlo>2*B), (
            "original translated endpoints unexpectedly coincide",n)
        distances[n]=min(abs(2*B-summlo),abs(2*B-summhi))

    # The source endpoint is cos(2*pi*C0*B).
    # EXACT rational angle: 2*B*C0=407/320;
    # a cosine zero would require q=1/2 mod integer.
    phase=2*B*C0
    assert phase==F(407,320)
    assert phase.denominator==320
    # Rigorous inherited exact-rational sin/cos with bounded Taylor
    # remainder and original interval pi enclosure.
    coslo,coshi=cos_sin_pi_multiple(phase)[1]
    assert coslo<coshi<0, "signed original endpoint phase must be nonzero"
    wlo,whi=WEIGHTS[2]  # ln(2)/sqrt(2), actual original multiplier
    assert 0<wlo<whi
    candidates=[w*c for w in (wlo,whi) for c in (coslo,coshi)]
    jumplo,jumphi=min(candidates),max(candidates)
    assert jumplo<jumphi<0

    # Fourier convention: original -2*w_n*cos(2*pi*xi*ln n)
    # contributes -w_n[v(x+ln n)+v(x-ln n)].
    # At x0, v(x+ln2) exits the support as x increases:
    # right-minus-left jump = +w_2*cos(2*pi*C0*B).
    assert jumphi < -F(1,4)  # source-specific strictly negative margin
    return {
        "cluster":C0, "xlo":x0lower,"xhi":x0upper,
        "phase":phase,"coslo":coslo,"coshi":coshi,
        "weight_lo":wlo,"weight_hi":whi,
        "jump_lo":jumplo,"jump_hi":jumphi,
        "n_edges":len(distances),"dim":469
    }


